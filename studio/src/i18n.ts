const MESSAGES: Record<Lang, Record<Key, string>> = { en, nb };
const STORE = "brasscribe.studio.lang";

function detect(): Lang {
  try {
    const saved = localStorage.getItem(STORE);
    if (saved === "en" || saved === "nb") return saved;
  } catch {
    /* storage may be blocked */
  }
  const langs = typeof navigator !== "undefined" ? navigator.languages ?? [navigator.language] : [];
  for (const l of langs) {
    const base = l.toLowerCase().split("-")[0];
    if (base === "nb" || base === "nn" || base === "no") return "nb";
    if (base === "en") return "en";
  }
  return "en";
}

let current: Lang = detect();
const listeners = new Set<(l: Lang) => void>();

export function lang(): Lang {
  return current;
}

/** BCP 47 tag for Intl formatting and the page's lang attribute. */
export function locale(): string {
  return current === "nb" ? "nb-NO" : "en-GB";
}

export function setLang(l: Lang): void {
  if (l === current) return;
  current = l;
  try {
    localStorage.setItem(STORE, l);
  } catch {
    /* storage may be blocked */
  }
  for (const f of listeners) f(l);
}

export function onLangChange(f: (l: Lang) => void): () => void {
  listeners.add(f);
  return () => listeners.delete(f);
}

/** Translate a key, filling {name} placeholders. Unknown keys come back unchanged. */
export function t(key: Key | string, vars: Record<string, string | number> = {}): string {
  const s = (MESSAGES[current] as Record<string, string>)[key] ?? (en as Record<string, string>)[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

