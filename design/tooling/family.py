"""The family's own look, made from the brands': design/brands/scribe/dist/web/.

Scribe is the family the products belong to. It has no app, so it has no token file of its own and no colour of its
own: its palette is what the brands have in common. For every neutral colour role, in every mode the brands'
generated web tokens have, the family's value is the midpoint of the brands' values, so it sits between brass and
blue ink and leans to neither. Three rules make it a place the brands stand out on:

  - it sits one step back: its background is the midpoint of the brands' `surface`, its `surface` the midpoint of
    their `secondary`, and its raised surface the midpoint of their backgrounds, so a brand's own page is the
    lightest thing on it;
  - it has no accent: `brand`, `accent` and `brand-text` are its text colour, `brand-tint` its raised surface;
  - it has no face of its own: the display face is the platform's.

Everything that is not a colour (spacing, type sizes, radii, motion) is the same in every brand and is taken as it is.
bar.css holds the three colours of the bar that is on every page of every product, the same in light and dark: the
family's light-mode ink, paper and muted text. The family's mark and how its name is set are in
design/brands/scribe/brand/.

    uv run design/tooling/family.py            write design/brands/scribe/dist/web/scribe.css, bar.css, fonts.css
    uv run design/tooling/family.py --check    exit 1 if they are out of date (after a brand's tokens change)
"""

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "design" / "brands" / "scribe" / "dist" / "web"
BRANDS = json.loads((HERE / "brands.json").read_text())["brands"]
STEP_BACK = {"bg": "surface", "surface": "secondary", "surface-raised": "bg"}
NO_ACCENT = {"brand": "text", "accent": "text", "brand-text": "text", "brand-tint": "surface-raised"}
HEADER = "/* Generated by design/tooling/family.py from the brands' generated web tokens. Do not edit. */\n"


RULE = re.compile(r"([^{}]*)\{([^{}]*)\}")
PROPERTY = re.compile(r"(--[\w-]+):\s*([^;]+);")
HEX = re.compile(r"#[0-9A-Fa-f]{6}")


def selector(before: str) -> str:
    """What a block of custom properties is for: its selector, without the comments before it."""
    return before.rsplit("*/", 1)[-1].strip()


def blocks(css: str) -> dict[tuple[str, int], dict[str, str]]:
    """A generated token file's blocks of custom properties, by selector and by which one of that selector it is
    (the same selector comes again under each @media)."""
    found, seen = {}, {}
    for m in RULE.finditer(css):
        props = dict(PROPERTY.findall(m.group(2)))
        if props:
            key = selector(m.group(1))
            seen[key] = seen.get(key, 0) + 1
            found[(key, seen[key])] = props
    return found


def midpoint(values: list[str]) -> str:
    mix = [round(sum(int(v[i:i + 2], 16) for v in values) / len(values)) for i in (1, 3, 5)]
    return "#" + "".join(f"{v:02X}" for v in mix)


def family() -> dict[str, str]:
    sources = [(ROOT / b["out"] / "web" / f'{b["name"]}.css').read_text() for b in BRANDS]
    others = [blocks(css) for css in sources[1:]]
    seen, bar = {}, {}

    def rewrite(m: re.Match) -> str:
        props = dict(PROPERTY.findall(m.group(2)))
        if not props:
            return m.group(0)
        key = selector(m.group(1))
        seen[key] = seen.get(key, 0) + 1
        theirs = [o.get((key, seen[key])) for o in others]
        if None in theirs:
            return ""  # a mode only one brand has (Brasscribe's pink) is not the family's
        colours = {}
        for name, value in props.items():
            values = [value] + [t.get(name, "") for t in theirs]
            if name.startswith("--scribe-") and all(HEX.fullmatch(v) for v in values):
                colours[name.removeprefix("--scribe-")] = midpoint(values)
        pad = re.match(r"[ \t]*", m.group(2).lstrip("\n")).group(0)
        lines = []
        for name, value in props.items():
            role = name.removeprefix("--scribe-")
            if not name.startswith("--scribe-"):
                continue  # a brand's own names are not the family's
            if role in colours:
                source = NO_ACCENT.get(role, role)
                value = colours[STEP_BACK.get(source, source)]
            elif role == "font-display":
                value = props["--scribe-font-text"]
            lines.append(f"{pad}{name}: {value};")
        if not bar:  # the first block is light mode
            bar.update({"--family-bar": colours["text"], "--family-bar-text": colours["bg"], "--family-bar-muted": colours["border"]})
        return f"{m.group(1)}{{\n" + "\n".join(lines) + f"\n{pad[:-2]}}}"

    css = RULE.sub(rewrite, sources[0])
    css = re.sub(r"\A(?:/\*.*?\*/\s*)+", "", css, flags=re.S)                 # the brand's own header
    css = re.sub(r"@media[^{}]*\{\s*\}\n*", "", css)                           # an @media left with nothing in it
    css = re.sub(r"/\*(?:(?!\*/).)*\*/\s*(?=/\*|@media|\Z)", "", css, flags=re.S)   # a comment left over nothing
    css = re.sub(r"\n{3,}", "\n\n", css)
    return {
        "scribe.css": HEADER + "/* Scribe, the family: every colour is the midpoint of the brands' (design/tooling/family.py says how). */\n\n" + css.lstrip(),
        "bar.css": HEADER + "/* The bar on every page of every product: the family's ink, paper and muted text, the same in light and dark. */\n:root {\n"
                   + "\n".join(f"  {k}: {v};" for k, v in bar.items()) + "\n}\n",
        "fonts.css": HEADER + "/* The family has no face of its own: its pages are set in the platform's. */\n",
    }


def main() -> int:
    made = family()
    if "--check" in sys.argv:
        stale = [name for name, text in made.items() if not (OUT / name).exists() or (OUT / name).read_text() != text]
        if stale:
            print("The family's outputs are out of date. Run `uv run design/tooling/family.py`:\n  " + "\n  ".join(stale))
            return 1
        print("the family's outputs are in sync: design/brands/scribe/dist/web")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in made.items():
        (OUT / name).write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
