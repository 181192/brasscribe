"""The family's own look, made from the brands': design/brands/scribe/dist/web/.

Scribe is the family the products belong to: the desk the products' sheets of paper are laid on, and the pen that
writes on them. It has no app, so it has no token file of its own and no colour of its own: its palette is what the
brands have in common. For every neutral colour role, in every mode the brands' generated web tokens have, the
family's value is the midpoint of the brands' values, so it sits between brass and blue ink and leans to neither.
These rules make it a desk the brands stand out on:

  - it sits one step back: its background is the midpoint of the brands' `surface`, its `surface` the midpoint of
    their `secondary`, and its raised surface the midpoint of their backgrounds, so a brand's own page is the
    lightest thing on it. In light mode the desk goes one step further back (background and surface trade places),
    so a sheet laid on it reads as paper on linen;
  - it has no accent: `brand`, `accent` and `brand-text` are its text colour, `brand-tint` its raised surface;
  - it has no face of its own: the display face is the platform's, set heavier and tighter than text (DISPLAY);
  - its one motif is the pen line: a line ending in a dot, always ink (PEN).

Everything that is not a colour (spacing, type sizes, radii, motion) is the same in every brand and is taken as it is.
line.css is what the family puts on every page of every product: the bar's three colours (the same in light and
dark: the family's light-mode ink, paper and muted text), each product's chip in the bar (its brand colour on a dark
ground), the pen line, the display face's weight and tracking, and the colour of the doubt mark in the site's own
figures (one for every product: DOUBT_FROM's `uncertain`, in each of its modes). variants/<name>.svg are the glyphs
of the places an app runs (design/tooling/icons.json, "variants"). The family's mark and how its name is set are in
design/brands/scribe/brand/.

    uv run design/tooling/family.py            write design/brands/scribe/dist/web/scribe.css, line.css, fonts.css, variants/
    uv run design/tooling/family.py --check    exit 1 if they are out of date (after a brand's tokens change)
"""

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "design" / "brands" / "scribe" / "dist" / "web"
BRANDS = json.loads((HERE / "brands.json").read_text())["brands"]
STEP_BACK = {"bg": "surface", "surface": "secondary", "surface-raised": "bg"}
DESK = {**STEP_BACK, "bg": "secondary", "surface": "surface"}  # light mode: one step further back
NO_ACCENT = {"brand": "text", "accent": "text", "brand-text": "text", "brand-tint": "surface-raised"}
PEN = {"pen-width": "2px", "pen-dot": "8px"}
DISPLAY = {"display-weight": "650", "display-tracking": "-0.02em"}
DOUBT_FROM = "fretscribe"  # its uncertain colour is AA on both brands' papers, and blue is its brand, not a doubt
DARK = ':root:not([data-theme="light"])'
ICONS = json.loads((HERE / "icons.json").read_text())["variants"]
GLYPH = ('<svg class="variant-glyph" viewBox="0 0 20 20" width="20" height="20" fill="none" stroke="currentColor" stroke-width="1.5" '
         'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">{}</svg>\n')
HEADER = "/* Generated by design/tooling/family.py from the brands' generated web tokens. Do not edit. */\n"


RULE = re.compile(r"([^{}]*)\{([^{}]*)\}")
PROPERTY = re.compile(r"(--[\w-]+):\s*([^;]+);")
HEX = re.compile(r"#[0-9A-Fa-f]{6}")


def selector(before: str) -> str:
    """What a block of custom properties is for: its selector, without the comments before it."""
    return before.rsplit("*/", 1)[-1].strip()


def blocks(css: str) -> dict[tuple[str, int], dict[str, str]]:
    """A generated token file's blocks of custom properties, by selector and by which one of that selector it is
    (the same selector comes again under each @media)."""
    found, seen = {}, {}
    for m in RULE.finditer(css):
        props = dict(PROPERTY.findall(m.group(2)))
        if props:
            key = selector(m.group(1))
            seen[key] = seen.get(key, 0) + 1
            found[(key, seen[key])] = props
    return found


def midpoint(values: list[str]) -> str:
    mix = [round(sum(int(v[i:i + 2], 16) for v in values) / len(values)) for i in (1, 3, 5)]
    return "#" + "".join(f"{v:02X}" for v in mix)


def family() -> dict[str, str]:
    sources = [(ROOT / b["out"] / "web" / f'{b["name"]}.css').read_text() for b in BRANDS]
    others = [blocks(css) for css in sources[1:]]
    seen, bar = {}, {}

    def rewrite(m: re.Match) -> str:
        props = dict(PROPERTY.findall(m.group(2)))
        if not props:
            return m.group(0)
        key = selector(m.group(1))
        seen[key] = seen.get(key, 0) + 1
        theirs = [o.get((key, seen[key])) for o in others]
        if None in theirs:
            return ""  # a mode only one brand has (Brasscribe's pink) is not the family's
        colours = {}
        for name, value in props.items():
            values = [value] + [t.get(name, "") for t in theirs]
            if name.startswith("--scribe-") and all(HEX.fullmatch(v) for v in values):
                colours[name.removeprefix("--scribe-")] = midpoint(values)
        pad = re.match(r"[ \t]*", m.group(2).lstrip("\n")).group(0)
        lines = []
        for name, value in props.items():
            role = name.removeprefix("--scribe-")
            if not name.startswith("--scribe-"):
                continue  # a brand's own names are not the family's
            if role in colours:
                source = NO_ACCENT.get(role, role)
                value = colours[(DESK if not bar else STEP_BACK).get(source, source)]
            elif role == "font-display":
                value = props["--scribe-font-text"]
            lines.append(f"{pad}{name}: {value};")
        if not bar:  # the first block is light mode
            bar.update({"--family-bar": colours["text"], "--family-bar-text": colours["bg"], "--family-bar-muted": colours["border"]})
        return f"{m.group(1)}{{\n" + "\n".join(lines) + f"\n{pad[:-2]}}}"

    css = tidy(RULE.sub(rewrite, sources[0]))
    chips = {f'--family-chip-{b["name"]}': blocks(src)[(DARK, 1)]["--scribe-brand"] for b, src in zip(BRANDS, sources)}
    line = {**bar, **chips, **{f"--family-{k}": v for k, v in {**PEN, **DISPLAY}.items()}}
    doubt = sources[[b["name"] for b in BRANDS].index(DOUBT_FROM)]

    def only_doubt(m: re.Match) -> str:
        found = PROPERTY.findall(m.group(2))
        value = dict(found).get("--scribe-uncertain")
        if value is None:
            return ""
        pad = re.match(r"[ \t]*", m.group(2).lstrip("\n")).group(0)
        return f"{m.group(1)}{{\n{pad}--family-doubt: {value};\n{pad[:-2]}}}"

    made = {
        "scribe.css": HEADER + "/* Scribe, the family: every colour is the midpoint of the brands' (design/tooling/family.py says how). */\n\n" + css.lstrip(),
        "line.css": HEADER + "/* What the family puts on every page of every product: the bar, each product's chip in it, the pen line, the\n"
                    "   display face's weight and tracking, and the doubt mark of the site's own figures. */\n:root {\n"
                    + "\n".join(f"  {k}: {v};" for k, v in line.items()) + "\n}\n\n" + tidy(RULE.sub(only_doubt, doubt)).lstrip(),
        "fonts.css": HEADER + "/* The family has no face of its own: its pages are set in the platform's. */\n",
    }
    for name, icon in ICONS.items():
        made[f"variants/{name}.svg"] = GLYPH.format(icon["svg"])
    return made


def tidy(css: str) -> str:
    """A generated token file with what was left out taken away: its header, empty @media, stray comments."""
    css = re.sub(r"\A(?:/\*.*?\*/\s*)+", "", css, flags=re.S)                 # the brand's own header
    css = re.sub(r"@media[^{}]*\{\s*\}\n*", "", css)                           # an @media left with nothing in it
    css = re.sub(r"/\*(?:(?!\*/).)*\*/\s*(?=/\*|@media|\Z)", "", css, flags=re.S)   # a comment left over nothing
    return re.sub(r"\n{3,}", "\n\n", css)


def main() -> int:
    made = family()
    if "--check" in sys.argv:
        stale = [name for name, text in made.items() if not (OUT / name).exists() or (OUT / name).read_text() != text]
        if stale:
            print("The family's outputs are out of date. Run `uv run design/tooling/family.py`:\n  " + "\n  ".join(stale))
            return 1
        print("the family's outputs are in sync: design/brands/scribe/dist/web")
        return 0
    for name, text in made.items():
        (OUT / name).parent.mkdir(parents=True, exist_ok=True)
        (OUT / name).write_text(text)
    for old in [OUT / "bar.css", *(OUT / "variants").glob("*.svg")]:
        if old.exists() and str(old.relative_to(OUT)) not in made:
            old.unlink()
    return 0


if __name__ == "__main__":
    sys.exit(main())
